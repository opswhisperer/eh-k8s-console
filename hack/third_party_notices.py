#!/usr/bin/env python3
"""Regenerate THIRD_PARTY_NOTICES.md from the Go modules compiled into the binary.

    python3 hack/third_party_notices.py

Needs the module cache populated (go mod download). Fails if a module's license can't be found or
classified, so a new dependency can't slip in unreviewed.
"""
import os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def go(*args):
    return subprocess.run(["go", *args], cwd=ROOT, check=True, capture_output=True, text=True).stdout

def classify(text):
    if "Apache License" in text:
        return "Apache-2.0"
    if "Redistribution and use in source and binary forms" in text:
        return "BSD-3-Clause" if "Neither the name" in text else "BSD-2-Clause"
    if "Permission is hereby granted, free of charge" in text:
        return "MIT"
    if "Permission to use, copy, modify, and/or distribute" in text or "ISC License" in text:
        return "ISC"
    if "Mozilla Public License" in text:
        return "MPL-2.0"
    return None

mods = sorted(set(go("list", "-deps", "-f",
    "{{if .Module}}{{if not .Module.Main}}{{.Module.Path}} {{.Module.Version}}{{end}}{{end}}",
    "./cmd/eh-k8s-console").split("\n")) - {""})
rows, notices, problems = [], [], []
for line in mods:
    path, version = line.split()
    d = go("list", "-m", "-f", "{{.Dir}}", f"{path}@{version}").strip()
    lic = next((f for f in sorted(os.listdir(d)) if f.upper().startswith(("LICENSE", "LICENCE", "COPYING"))), None)
    kind = classify(open(os.path.join(d, lic), errors="replace").read(4000)) if lic else None
    if not kind:
        problems.append(f"{path} {version}: license not found or not recognised")
        continue
    rows.append((path, version, kind))
    for n in ("NOTICE", "NOTICE.txt", "NOTICE.md"):
        p = os.path.join(d, n)
        if os.path.isfile(p):
            notices.append((path, version, open(p, errors="replace").read().strip()))
if problems:
    sys.exit("\n".join(problems))

out = ["# Third-party notices", "",
"eh-k8s-console is licensed under the Apache License 2.0 (see `LICENSE`). The binary and container",
"image include the open-source Go modules below, each under its own license. The full license texts",
"ship with each module (see the module source at the version listed).", "",
"Generated by `python3 hack/third_party_notices.py` from `go list -deps ./cmd/eh-k8s-console`; it",
"covers only modules compiled into the binary. Regenerate it when dependencies change.", "",
"| Module | Version | License |", "|---|---|---|"]
out += [f"| [{m}](https://pkg.go.dev/{m}@{v}) | {v} | {k} |" for m, v, k in rows]
out += ["", "## Other components", "",
"| Component | Use | License |", "|---|---|---|",
"| [Go](https://go.dev) standard library | Compiled into the binary | BSD-3-Clause |",
"| [distroless/static](https://github.com/GoogleContainerTools/distroless) | Container base image (includes CA certificates) | Apache-2.0 |",
"| [Source Sans 3](https://github.com/adobe-fonts/source-sans) by Adobe | UI typeface, loaded from Google Fonts at runtime (not bundled) | SIL Open Font License 1.1 |",
"", "## Trademarks", "",
"ExtraHop, the ExtraHop logo and RevealX are trademarks of ExtraHop Networks, Inc. The logo files in",
"`web/static/brand/` belong to ExtraHop Networks and are **not** covered by this project's Apache-2.0",
"license. They are used only to identify the product this tool works with. See `NOTICE`."]
if notices:
    out += ["", "## NOTICE files from dependencies", "",
    "Apache-2.0 dependencies that ship a NOTICE file, reproduced as section 4(d) of that license requires.", ""]
    for m, v, t in notices:
        out += [f"### {m} {v}", "", "```", t, "```", ""]
open(os.path.join(ROOT, "THIRD_PARTY_NOTICES.md"), "w").write("\n".join(out).rstrip() + "\n")
print(f"{len(rows)} modules, {len(notices)} NOTICE files")
